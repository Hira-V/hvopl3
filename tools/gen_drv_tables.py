# gen_drv_tables.py -- writes drv/hvopl3_drv_tables.inc: the hirav level curve, the pitch exponent and
# the vibrato's sine. The output is checked in, so a build needs no libm.
#
import math, sys
from fractions import Fraction

HEADER = ['hvopl3 -- A new FM synth modeled on the Yamaha OPL3, with accelerated paths for Hira-V', 'Copyright (C) 2026 Kevin H. Patterson', 'SPDX-License-Identifier: BSD-3-Clause (see LICENSE.txt)', 'Hira-V: https://hira-v.com']
def rows(name, ty, vals, per=12):
    s = 'static constexpr %s %s[%d] = {\n' % (ty, name, len(vals))
    for i in range(0, len(vals), per):
        s += '\t' + ','.join(str(v) for v in vals[i:i + per]) + ',\n'
    return s + '};\n'
out = (''.join('// ' + l + '\n' for l in HEADER) + '//\n'
       '// hvopl3_drv_tables.inc -- generated by tools/gen_drv_tables.py; do not edit.\n//\n')
# hirav (General MIDI's curve, GM2 3.3.1): 40 log10(127 / x) dB, in the chip's 0.75 dB steps. x = 0 is
# silent, which the driver tests before reading the table. Q32 in 64 bits: four of them summed and rounded
# once give the formula's rounding for every one of the 127^4 sums (tests/t_drv.cpp checks them all).
out += '// 40 log10(127 / x) dB in 0.75 dB steps, Q32 (x = 0: silent, never read)\n'
out += rows('HIRAV_Q32', 'uint64_t', [0] + ['%dull' % round(40 * math.log10(127 / x) / 0.75 * (1 << 32)) for x in range(1, 128)], 4)
# Pitch: units of 1/4096 semitone, 49152 an octave. fnum x 2^block = f x 2^20 / (14318180 / 288), so its log2
# in units is key x 4096 + PITCH_BASE, A4 (69) = 440 Hz.
chip = Fraction(14318180, 288)
base = 49152 * math.log2(440 * (1 << 20) / chip) - 69 * 4096
out += '// log2(fnum x 2^block) of note 0, in 1/4096 semitone: A4 = 440 Hz, the chip at 14318180 / 288 Hz\n'
out += 'static constexpr int32_t PITCH_BASE = %d;\n' % round(base)
out += '// 2^(i / 768) in Q30: an octave in 768 steps of 64 units, each interpolated\n'
out += rows('EXP2_Q30', 'uint32_t', [round(2 ** (i / 768) * (1 << 30)) for i in range(769)], 8)
out += '// the driver vibrato\'s sine, Q14, 256 steps a cycle\n'
out += rows('VIB_SIN', 'int16_t', [round(math.sin(2 * math.pi * i / 256) * 16384) for i in range(256)], 16)
open(sys.argv[1], 'w').write(out)
