# gen_tables.py -- writes src/hvopl3_tables.inc: the log-sine and exponent ROMs by their published
# formulas, the pan law and the gain steps. The output is checked in, so a build needs no libm.
#
import math, sys

HEADER = ['hvopl3 -- A new FM synth modeled on the Yamaha OPL3, with accelerated paths for Hira-V', 'Copyright (C) 2026 Kevin H. Patterson', 'SPDX-License-Identifier: BSD-3-Clause (see LICENSE.txt)', 'Hira-V: https://hira-v.com']
def rows(name, ty, vals, per=16):
    s = 'static constexpr %s %s[%d] = {\n' % (ty, name, len(vals))
    for i in range(0, len(vals), per):
        s += '\t' + ','.join(str(v) for v in vals[i:i + per]) + ',\n'
    return s + '};\n'
x = [max(p - 1, 0) / 126 for p in range(128)]
out = (''.join('// ' + l + '\n' for l in HEADER) + '//\n'
       '// hvopl3_tables.inc -- generated by tools/gen_tables.py; do not edit.\n//\n')
out += rows('LOGSIN', 'uint16_t', [round(-math.log2(math.sin((i + .5) * math.pi / 512)) * 256) for i in range(256)])
out += rows('EXPO', 'uint16_t', [round((2 ** (i / 256) - 1) * 1024) for i in range(256)])
out += rows('PAN_L', 'uint16_t', [round(math.cos(v * math.pi / 2) * 32768) for v in x])
out += rows('PAN_R', 'uint16_t', [round(math.sin(v * math.pi / 2) * 32768) for v in x])
out += rows('GAIN', 'uint32_t', [round(10 ** (.75 * l / 20) * 16384) for l in range(-32, 33)])
open(sys.argv[1], 'w').write(out)
